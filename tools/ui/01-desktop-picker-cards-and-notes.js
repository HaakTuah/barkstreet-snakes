check(now[1] === pickKey && now[0] === before[0] && now[2] === before[2] && pk.chosen && !pk.open && pk.game, 'picking a rival seats it there (the others stay), marked chosen, and the round counts as chosen', `${now} ${JSON.stringify(pk)}`);
